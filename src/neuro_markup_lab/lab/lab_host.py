"""
Вспомогательные данные от приложения-хозяина.

Хозяин наследует :class:`MarkupLabHost` и переопределяет только то, что знает. Методы вызываются
на каждый запрос, поэтому данные из базы хозяина всегда свежие. Новые данные добавляются новым
методом со значением «не знаю» по умолчанию — прежние хозяева продолжают работать без правок.
"""

__all__ = ['MarkupLabHost']

from collections.abc import Sequence
from pathlib import Path


class MarkupLabHost:
    """ Данные хозяина для редактора разметки. По умолчанию хозяин ничего не знает. """

    def markup_key(self, video: Path) -> str | None:
        """ Ключ боевой разметки видео (имя файла в каталоге без ``.json``); ``None`` — подобрать по каталогу. """
        return None

    def factories(self) -> Sequence[str]:
        """ Известные производства: показываются у видео и помогают выбрать между равными файлами. """
        return ()
